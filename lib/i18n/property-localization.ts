export function translatePropertyValue(value: unknown, language: Language): string {
  const text = value == null ? '' : String(value)
  if (language !== 'en' || !text) return text
  return VALUE_TRANSLATIONS[text] || VALUE_TRANSLATIONS[text.replaceAll('_', ' ')] || text
}

export function translatePropertyTitle(value: unknown, language: Language): string {
  const text = value == null ? '' : String(value)
  if (language !== 'en' || !text) return text
  return TITLE_PATTERNS.reduce((translated, [pattern, replacement]) => translated.replace(pattern, replacement), text)
}

export function translatePropertyList(values: string[] | undefined, language: Language): string[] {
  return (values || []).map(value => translatePropertyValue(value, language))
}
